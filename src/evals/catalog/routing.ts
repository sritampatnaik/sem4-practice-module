type RoutingSpec = {
  id: string;
  title: string;
  prompt: string;
  profile: StudentProfile;
  contract: string;
  routing: Required<GoldRouting>;
};

function makeRoutingItem(spec: RoutingSpec): EvalItem {
  return {
    id: spec.id,
    suiteId: "routing",
    kind: "routing",
    title: spec.title,
    prompt: spec.prompt,
    profile: spec.profile,
    targetAgent: "orchestration",
    scaffold: {
      contract: spec.contract,
      goldReply: JSON.stringify(spec.routing),
      routing: spec.routing,
      source: "routing-catalog",
    },
  };
}

